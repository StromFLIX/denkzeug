"""Generate the staging-only Rust broker wiring without changing production Compose.

Coolify's trusted Temporal hooks invoke sh and Python in docker-broker. Retain the
existing maintenance runtime for this staging trial; only Rust serves HTTP.
"""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "# Generated by scripts/sync_rust_broker_staging.py; do not edit directly.\n"


def generated(root: Path = ROOT) -> dict[Path, str]:
    compose = (root / "docker-compose.yaml").read_text()
    old = "dockerfile: services/docker-broker/Dockerfile"
    if compose.count(old) != 1:
        raise ValueError("Expected exactly one production broker Dockerfile reference")
    staging = HEADER + compose.replace(old, "dockerfile: services/docker-broker-rust/Dockerfile.staging")
    rust = (root / "services/docker-broker-rust/Dockerfile.spike").read_text()
    compile_stage, separator, _ = rust.partition("\nFROM scratch AS candidate")
    if not separator:
        raise ValueError("Cannot find the canonical Rust compiler stage")
    python = (root / "services/docker-broker/Dockerfile").read_text()
    command = 'CMD ["uvicorn", "nautionette_docker_broker.main:app", "--host", "0.0.0.0", "--port", "9100"]'
    if python.count(command) != 1:
        raise ValueError("Expected the canonical Python broker entrypoint")
    python = python.replace(command, "")
    compatibility = (
        HEADER
        + "# Rust HTTP runtime; Python/sh retained only for trusted Coolify maintenance hooks.\n"
        + compile_stage.rstrip()
        + "\n\n"
        + python.rstrip()
        + "\nCOPY --from=compile /broker /broker\n"
        + "ENV BROKER_BIND_ADDR=0.0.0.0 BROKER_PORT=9100 BROKER_DOCKER_SOCKET=/var/run/docker.sock\n"
        + 'CMD ["/broker", "--local-runtime"]\n'
    )
    return {
        root / "docker-compose.rust-staging.yaml": staging,
        root / "services/docker-broker-rust/Dockerfile.staging": compatibility,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated staging files drift")
    args = parser.parse_args()
    for path, content in generated().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale staging wiring: {path.relative_to(ROOT)}; run this script")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
